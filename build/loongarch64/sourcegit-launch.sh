#!/bin/bash
# ---------------------------------------------------------------------------
# SourceGit (loongarch64) launcher with a workaround for the
# "打开文件夹 / Open Folder crashes the app" bug.
#
# Why this exists
# ---------------
# libSkiaSharp.so (SkiaSharp 2.88.9) statically links FreeType 2.13.1 and exports
# every FT_* symbol with GLOBAL visibility. The .NET host loads it with RTLD_GLOBAL,
# so those symbols preempt the system libfreetype.so.6 (FreeType 2.11.1) that
# fontconfig / pango / GTK3 use. The two FreeType ABIs are incompatible
# (FT_Palette changed from FT_Color* to a struct in 2.12+), therefore:
#
#   * GTK cannot render any text  -> "drawing failure for widget ... libfreetype"
#   * pango frees a corrupted chunk -> glibc abort: "munmap_chunk(): invalid pointer"
#
# The crash only happens when Avalonia opens the *native* GTK file/folder picker
# (Avalonia.X11 -> GtkSystemDialog), i.e. when you click 打开文件夹.
#
# The fix
# -------
# Make dlopen("libgtk-3.so.0") fail for this process. Avalonia's
# FallbackStorageProvider then skips the GTK dialog and uses its own managed
# picker (Avalonia.Dialogs.ManagedStorageProvider), which is pure Avalonia and
# therefore cannot hit the FreeType conflict.
# ---------------------------------------------------------------------------
set -e

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# The published app lives in the (git ignored) `out/` folder of the repository.
OUT_DIR="$(cd "$DIR/../../out" 2>/dev/null && pwd || echo "$DIR/../../out")"
APP="$OUT_DIR/linux-loongarch64/SourceGit"

[ -x "$APP" ] || { echo "SourceGit binary not found: $APP" >&2; exit 1; }

STUB="$OUT_DIR/no-gtk"
mkdir -p "$STUB"
# An invalid ELF image: dlopen() fails on it, so Avalonia never uses GTK.
printf 'libgtk-3.so.0 is intentionally disabled - see CRASH-ANALYSIS-freetype-gtk.md\n' \
    > "$STUB/libgtk-3.so.0"

export LD_LIBRARY_PATH="$STUB${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"

# Put the self-installed Git (2.56.1) in front of the system one (2.20.1).
# Desktop sessions / autostart have a minimal PATH without ~/.local/bin, and
# SourceGit would then pick /usr/bin/git 2.20.1, which does not know the
# `%(worktreepath)` atom (needs Git >= 2.31) and silently returns an empty
# branch list. See sessions/2026-11-10-修复本机分支显示0个.md.
export PATH="$HOME/.local/bin:$PATH"

# Git version self-check: the `%(worktreepath)` atom needs Git >= 2.31.
# An older Git makes `git branch --format` fail as a whole, and SourceGit
# silently ends up with an empty branch list. Warn instead of failing silently.
# (Keep in sync with the wrapper generated by pack-deb-loongarch64.sh)
git_ver="$(git --version 2>/dev/null | awk '{print $3}')"
if [ -n "$git_ver" ]; then
    g_major="${git_ver%%.*}"
    g_rest="${git_ver#*.}"
    g_minor="${g_rest%%.*}"
    if [ "$g_major" -eq 2 ] 2>/dev/null && [ "$g_minor" -lt 31 ] 2>/dev/null; then
        echo "警告：当前 git 为 $git_ver（$(command -v git)），低于 SourceGit 分支列表所需的 2.31，" >&2
        echo "       分支树可能显示为空。请安装新版 git（如 ~/.local/bin/git），" >&2
        echo "       并在偏好设置的「Git 安装路径」里指定它。" >&2
    fi
fi

exec "$APP" "$@"
